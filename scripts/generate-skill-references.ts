function errorsMarkdown(): string {
  const families = new Map<string, string[]>();
  for (const code of Object.values(ERROR_CODES)) {
    const family = errorFamily(code);
    const lines = families.get(family) ?? [];
    lines.push(`- \`${code}\` — ${ERROR_GUIDANCE[code]}`);
    families.set(family, lines);
  }

  const sections = [...families.entries()]
    .map(([family, lines]) => `## ${family}_*\n\n${lines.join('\n')}`)
    .join('\n\n');

  return `# Error codes and what to do about them

${GENERATED_NOTE}

Every Agentship error carries \`code\`, \`message\`, \`retryable\` and usually a \`remediation\`.
Read the remediation first: it is written for you to relay. Codes are grouped by family, so
you can react to a class of failure without knowing every member.

${sections}

## Rules

- Never invent a fix that contradicts the remediation.
- \`retryable: true\` (rate limits, store outages, download failures) is the only case where
  repeating the same call unchanged is reasonable.
- A failed apply never needs cleaning up by hand: call \`agentship_resume\`, which re-reads the
  journal and the store and continues from the real state.
`;
}

async function writeIfChanged(path: string, content: string): Promise<void> {
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, content);
  console.log(`wrote ${path}`);
}

export function generatedFiles(): Record<string, string> {
  const stores = storesMarkdown();
  return {
    [join(SKILLS_DIR, 'agentship-publish/references/stores.md')]: stores,
    [join(SKILLS_DIR, 'agentship-first-release/references/stores.md')]: stores,
    [join(SKILLS_DIR, 'agentship-troubleshoot/references/errors.md')]: errorsMarkdown(),
  };
}

const invokedDirectly =
  process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (invokedDirectly) {
  for (const [path, content] of Object.entries(generatedFiles())) {
    await writeIfChanged(path, content);
  }
}
