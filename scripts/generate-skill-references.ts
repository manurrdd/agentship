function pendingSection(operations: readonly PendingOperation[]): string {
  return operations
    .map(
      (operation) =>
        `- **${operation.title}** (\`${operation.id}\`, ${operation.actionClass}) — ${operation.reason}${
          operation.console === undefined ? '' : ` Console: ${operation.console.url}`
        }`,
    )
    .join('\n');
}

function storesMarkdown(): string {
  const rows = OPERATION_IDS.map(
    (id) =>
      `| ${OPERATION_SUMMARIES[id]} | \`${id}\` | ${APPLE_CAPABILITIES[id]} | ${GOOGLE_CAPABILITIES[id]} |`,
  ).join('\n');

  return `# What the stores let Agentship do

${GENERATED_NOTE}

This is the real coverage table of both adapters. Use it to answer "can you do X?" honestly
before promising anything, and to know in advance which parts of a release will need the user.

| Operation | Id | Apple | Google |
|---|---|---|---|
${rows}

## What each classification means for you

${Object.entries(CLASS_MEANING)
  .map(([name, meaning]) => `- **${name}** — ${meaning}`)
  .join('\n')}

The classification in a plan can be stricter than this table: pricing, privacy declarations,
review submissions, destructive changes and anything reaching production are always
\`needs_approval\`, even where the store would allow Agentship to act alone.

## Console-only work known before any plan

### App Store Connect
${pendingSection(APPLE_PENDING_OPERATIONS)}

### Google Play
${pendingSection(GOOGLE_PENDING_OPERATIONS)}

## Two limits worth telling the user early

- A new personal Google Play account must run a closed test with at least 12 testers for 14
  continuous days before it can publish to production. It cannot be bypassed; plan for it.
- Apple issues the App Store Connect \`.p8\` key file exactly once. If it is lost, the key has
  to be revoked and a new one generated.
`;
}

